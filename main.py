# История сообщений
history = [
    {"role": "system", "content": SYSTEM_PROMPT},
    {"role": "user", "content": "Пожалуйста, опишите ваши черты, поведение и жизненные опыты, которые вы хотели бы, чтобы я проанализировал, и я начну процесс."}
]

def chat_with_llama(user_input: str):
    history.append({"role": "user", "content": user_input})

    payload = {
        "model": MODEL_NAME,
        "messages": history,
        "stream": False
    }

    headers = {"Content-Type": "application/json"}
    response = requests.post(OLLAMA_URL, headers=headers, data=json.dumps(payload))

    if response.status_code == 200:
        data = response.json()
        reply = data["message"]["content"]
        print("\n🧠 Ответ модели:\n")
        print(reply)
        print("\n" + "-" * 60 + "\n")
        history.append({"role": "assistant", "content": reply})
    else:
        print(f"❌ Ошибка: {response.status_code} — {response.text}")

if __name__ == "__main__":
    print("🧠 Психолог-Деконструктор активен.")
    print("Введите 'выход' для завершения.\n")

    chat_with_llama("Пожалуйста, опишите ваши черты, поведение и жизненные опыты, которые вы хотели бы, чтобы я проанализировал, и я начну процесс.")  # бот начинает диалог

    while True:
        user_input = input("Вы: ")
        if user_input.strip().lower() in ["выход", "quit", "exit"]:
            print("До свидания!")
            break
        chat_with_llama(user_input)
